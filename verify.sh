#!/usr/bin/env bash
# Independently verify a wordpress-studio-bin package: rebuild it on YOUR
# machine from Automattic's .deb with the exact build.sh that CI used, and
# check that the result matches the published package.
#
#   ./verify.sh                      verify the package currently in the repo
#   ./verify.sh <file.pkg.tar.zst>   verify a specific file, e.g. the one you
#                                    installed: /var/cache/pacman/pkg/wordpress-studio-bin-*.pkg.tar.zst
#
# What "match" means: every file's contents (sha256), type, permissions,
# owner, size and symlink target; the install script (.INSTALL, which pacman
# runs as root); and the package metadata (.PKGINFO: version, dependencies,
# provides/conflicts/replaces). Not compared: .BUILDINFO (records the build
# machine's tool versions) and .MTREE (an index derived from the files above),
# nor the compressed archive bytes (depend on the zstd version).
#
# Needs: curl, bsdtar, makepkg + fakeroot (base-devel), ar (binutils). Downloads ~550 MB.
set -euo pipefail

REPO="kossmann/wordpress-studio-arch-linux"
BASE="https://github.com/$REPO/releases/download/repo"
RAW="https://raw.githubusercontent.com/$REPO"
CURL=(curl -fsSL --proto '=https' --proto-redir '=https' --max-redirs 5)

die()  { printf '\033[1;31mFAIL:\033[0m %s\n' "$*" >&2; exit 1; }
log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }

for t in curl bsdtar makepkg fakeroot ar sha256sum; do
  command -v "$t" >/dev/null || die "missing '$t' (install base-devel and binutils)"
done

here=$(cd "$(dirname "$0")" && pwd)
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT

# 1. The package to verify.
if [[ $# -ge 1 ]]; then
  pkg=$(realpath "$1"); [[ -f "$pkg" ]] || die "no such file: $1"
else
  log "fetching the current package from the repo"
  "${CURL[@]}" -o "$work/repo.db" "$BASE/wordpress-studio.db"
  name=$(tar -xzOf "$work/repo.db" --wildcards '*/desc' | awk '/^%FILENAME%$/{getline; print; exit}')
  [[ "$name" =~ ^wordpress-studio-bin-[A-Za-z0-9._]+-[0-9]+-x86_64\.pkg\.tar\.zst$ ]] || die "unexpected file name in repo db: $name"
  "${CURL[@]}" -o "$work/$name" "$BASE/$name"
  pkg="$work/$name"
fi
pkgsha=$(sha256sum "$pkg" | awk '{print $1}')
log "package: $(basename "$pkg")"
log "sha256:  $pkgsha"

# 2. Find it in HISTORY.md: which vendor .deb and which build.sh commit made it.
"${CURL[@]}" -o "$work/HISTORY.md" "$RAW/main/HISTORY.md"
row=$(grep -F "\`$pkgsha\`" "$work/HISTORY.md" | tail -n1) \
  || die "this file's sha256 is not in HISTORY.md - it was not published by this repo's CI"
IFS='|' read -r _ _date pkgid debver url debsha _pkgsha commitcell _ <<<"$row"
strip() { local v="${1//\`/}"; v="${v#"${v%%[![:space:]]*}"}"; printf '%s' "${v%"${v##*[![:space:]]}"}"; }
pkgid=$(strip "$pkgid"); debver=$(strip "$debver"); url=$(strip "$url"); debsha=$(strip "$debsha")
commit=$(grep -oE 'commit/[0-9a-f]{40}' <<<"$commitcell" | cut -d/ -f2)
pkgrel="${pkgid##*-}"
[[ -n "$commit" && "$pkgrel" =~ ^[0-9]+$ && "$url" == https://appscdn.wordpress.com/* ]] \
  || die "could not parse the HISTORY.md row: $row"
log "built from: $url"
log "vendor version $debver, pkgrel $pkgrel, build.sh at commit $commit"

# 3. Get build.sh at that commit - from your local clone if you have one.
if git -C "$here" cat-file -e "$commit:build.sh" 2>/dev/null; then
  git -C "$here" show "$commit:build.sh" > "$work/build.sh"
  log "using build.sh from your local clone"
else
  "${CURL[@]}" -o "$work/build.sh" "$RAW/$commit/build.sh"
  log "using build.sh from $RAW/$commit/build.sh"
fi

# 4. Rebuild, with a clean environment.
log "rebuilding (downloads the vendor .deb, ~240 MB)"
env -i HOME="$HOME" PATH=/usr/bin:/bin LANG=C.UTF-8 \
  bash "$work/build.sh" build "$url" "$debver" "$pkgrel" "$work/rebuild" >"$work/build.log" 2>&1 \
  || { tail -n 20 "$work/build.log" >&2; die "rebuild failed (log above)"; }
rebuilt=$(ls "$work"/rebuild/*.pkg.tar.zst)

got_debsha=$(awk '{print $1}' "$work/rebuild/vendor-deb.sha256")
[[ "$got_debsha" == "$debsha" ]] \
  || die "Automattic's .deb at that URL now has sha256 $got_debsha, but CI recorded $debsha. The vendor file changed since it was published."
log "vendor .deb sha256 matches what CI recorded: $debsha"

# 5. Compare.
manifest() {
  bsdtar -cf - --format=mtree --options='!all,type,mode,uid,gid,size,link,sha256' \
    --exclude .BUILDINFO --exclude .MTREE --exclude .PKGINFO "@$1"
}
pkginfo() { bsdtar -xOf "$1" .PKGINFO | grep -v '^#'; }   # drop the "generated by makepkg X" comment lines

manifest "$pkg"     > "$work/published.mtree"
manifest "$rebuilt" > "$work/rebuilt.mtree"
pkginfo  "$pkg"     > "$work/published.pkginfo"
pkginfo  "$rebuilt" > "$work/rebuilt.pkginfo"

ok=1
if ! diff -q "$work/published.mtree" "$work/rebuilt.mtree" >/dev/null; then
  ok=0; echo "Files differ (published < > rebuilt):"; diff "$work/published.mtree" "$work/rebuilt.mtree" | head -n 40
fi
if ! diff -q "$work/published.pkginfo" "$work/rebuilt.pkginfo" >/dev/null; then
  ok=0; echo ".PKGINFO differs (published < > rebuilt):"; diff "$work/published.pkginfo" "$work/rebuilt.pkginfo"
fi
[[ $ok == 1 ]] || die "the published package does NOT match a fresh build"

entries=$(grep -c '^\./' "$work/published.mtree" || true)
printf '\033[1;32mVERIFIED:\033[0m %s\n' "$(basename "$pkg")"
cat <<EOF
  All $entries entries (contents, permissions, owners, symlinks), the install
  script and the package metadata are identical to a fresh build on this
  machine of Automattic's .deb (sha256 $debsha)
  using build.sh at commit $commit.

  Also check the build provenance (needs the gh CLI):
    gh attestation verify "$pkg" --repo $REPO
EOF
